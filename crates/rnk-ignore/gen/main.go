func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: gen <crate directory>")
		os.Exit(2)
	}
	dir := os.Args[1]
	write(filepath.Join(dir, "src", "unicode_tables.rs"), tables())
	write(filepath.Join(dir, "tests", "golden", "matcher.txt"), matcherGolden())
	write(filepath.Join(dir, "tests", "golden", "readall.txt"), readAllGolden())
	write(filepath.Join(dir, "tests", "golden", "walk.txt"), walkGolden())
}

// scale multiplies the number of random cases (GEN_SCALE, default 1), for
// a one-off deeper comparison; the committed goldens use 1.
func scale() int {
	s := os.Getenv("GEN_SCALE")
	if s == "" {
		return 1
	}
	n, err := strconv.Atoi(s)
	if err != nil || n < 1 {
		panic("GEN_SCALE must be a positive integer")
	}
	return n
}

func write(path, content string) {
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		panic(err)
	}
}

func enc(s string) string {
	if s == "" {
		return "%"
	}
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c > 0x20 && c < 0x7f && c != '%' {
			b.WriteByte(c)
		} else {
			fmt.Fprintf(&b, "%%%02X", c)
		}
	}
	return b.String()
}

