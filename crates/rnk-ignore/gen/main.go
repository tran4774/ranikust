// Command gen writes rnk-ignore's Unicode tables and test goldens from the
// Go code that ranikust must match: moby/patternmatcher v0.6.1 (used by
// BuildKit v0.34.0 and the docker CLI), tonistiigi/fsutil at BuildKit
// v0.34.0's pin, and the Go standard library it is built with (go1.26.9).
//
// Usage: go run . <crate directory>
//
// It writes:
//
//   - src/unicode_tables.rs: the tables behind Go's regexp \p{...} classes;
//   - tests/golden/matcher.txt: patterns and paths with the results of
//     PatternMatcher.MatchesOrParentMatches and of MatchesUsingParentResults
//     chained along the path, as BuildKit's walk does;
//   - tests/golden/readall.txt: .dockerignore contents and the patterns
//     ignorefile.ReadAll returns;
//   - tests/golden/walk.txt: a directory tree, pattern lists, and the paths
//     fsutil's filtered walk reports.
//
// Every string in a golden is percent-encoded: bytes outside 0x21..0x7E,
// and '%', become %XX; the empty string is a lone '%'. The output only
// depends on the fixed seeds below.
//
// The exp-04 cases come from ranikust's experiment 04; canonicalName is
// copied from Go's regexp/syntax (Copyright 2011 The Go Authors, BSD
// 3-Clause); see NOTICE.
