type matcherCase struct {
	name     string
	file     *string // set when the patterns come from ignorefile.ReadAll
	patterns []string
	paths    []string
}

func matcherGolden() string {
	var cases []matcherCase
	for i, c := range exp04Cases {
		content := strings.Join(c, "\n")
		cases = append(cases, matcherCase{name: fmt.Sprintf("exp-04 case %d", i+1), file: &content, paths: exp04Paths})
	}
	for _, f := range kanikoFiles {
		content := f.content
		cases = append(cases, matcherCase{name: f.name, file: &content, paths: kanikoPaths})
	}
	r := rand.New(rand.NewPCG(1, 2))
	for i := 0; i < 1200*scale(); i++ {
		pats := randomPatterns(r)
		cases = append(cases, matcherCase{name: fmt.Sprintf("random %d", i+1), patterns: pats, paths: randomPaths(r, pats)})
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n", fmt.Sprintf(header, runtime.Version()))
	b.WriteString("# case <name>; file <content> when the patterns come from ReadAll;\n")
	b.WriteString("# pattern <p> per pattern given to New; new ok|err;\n")
	b.WriteString("# path <path> <MatchesOrParentMatches> <MatchesUsingParentResults along the path>,\n")
	b.WriteString("# each 0 (false), 1 (true) or E (error).\n")
	for _, c := range cases {
		fmt.Fprintf(&b, "case %s\n", enc(c.name))
		pats := c.patterns
		if c.file != nil {
			fmt.Fprintf(&b, "file %s\n", enc(*c.file))
			var err error
			pats, err = ignorefile.ReadAll(strings.NewReader(*c.file))
			if err != nil {
				panic(err)
			}
		}
		for _, p := range pats {
			fmt.Fprintf(&b, "pattern %s\n", enc(p))
		}
		pm, err := patternmatcher.New(pats)
		if err != nil {
			b.WriteString("new err\n")
			continue
		}
		b.WriteString("new ok\n")
		for _, p := range c.paths {
			p = strings.TrimSuffix(p, "/")
			fmt.Fprintf(&b, "path %s %s %s\n", enc(p), mopm(pm, p), walkChain(pm, p))
		}
	}
	return b.String()
}

func result(m bool, err error) string {
	switch {
	case err != nil:
		return "E"
	case m:
		return "1"
	default:
		return "0"
	}
}

func mopm(pm *patternmatcher.PatternMatcher, p string) string {
	return result(pm.MatchesOrParentMatches(p))
}

// walkChain calls MatchesUsingParentResults on each prefix of p, passing
// the previous result's MatchInfo, as fsutil's walk does.
func walkChain(pm *patternmatcher.PatternMatcher, p string) string {
	parts := strings.Split(p, "/")
	info := patternmatcher.MatchInfo{}
	var m bool
	var err error
	for i := range parts {
		m, info, err = pm.MatchesUsingParentResults(strings.Join(parts[:i+1], "/"), info)
		if err != nil {
			return "E"
		}
	}
	return result(m, nil)
}

