var walkWords = []string{
	"a", "b", "c", "foo", "bar", "sub", "docs", "keep.md", "a.txt", "temp*", "tempdir", "node_modules", "ignore",
	"odd", "x", "y", "*", "*", "**", "?", "*.txt", "*.md", "[a-c]", "\xc3\xa9*", "\xff", "sp ace", ".git",
}

// randomWalkPatterns mostly excludes something broad first and re-includes
// parts of it later, the case where the walk's pruning matters.
func randomWalkPatterns(r *rand.Rand) []string {
	n := 1 + r.IntN(4)
	var out []string
	for i := range n {
		var b strings.Builder
		if i > 0 && r.IntN(3) != 0 {
			b.WriteString("!")
		}
		if i == 0 && r.IntN(2) == 0 {
			out = append(out, []string{"*", "**", "*/*", "docs", "sub", "a", "foo", "odd", "ignore", "*/"}[r.IntN(10)])
			continue
		}
		segs := 1 + r.IntN(3)
		for s := range segs {
			if s > 0 {
				b.WriteString("/")
			}
			b.WriteString(walkWords[r.IntN(len(walkWords))])
		}
		if r.IntN(6) == 0 {
			b.WriteString("/**")
		}
		out = append(out, b.String())
	}
	return out
}

func walkGolden() string {
	root, err := os.MkdirTemp("", "rnk-ignore-walk")
	if err != nil {
		panic(err)
	}
	defer os.RemoveAll(root)
	for _, e := range treeEntries {
		p := filepath.Join(root, e)
		if strings.HasSuffix(e, "/") {
			err = os.MkdirAll(p, 0o755)
		} else {
			err = os.WriteFile(p, nil, 0o644)
		}
		if err != nil {
			panic(err)
		}
	}

	var cases [][]string
	for _, c := range exp04Cases {
		pats, err := ignorefile.ReadAll(strings.NewReader(strings.Join(c, "\n")))
		if err != nil {
			panic(err)
		}
		cases = append(cases, pats)
	}
	for _, f := range kanikoFiles {
		pats, err := ignorefile.ReadAll(strings.NewReader(f.content))
		if err != nil {
			panic(err)
		}
		cases = append(cases, pats)
	}
	r := rand.New(rand.NewPCG(5, 6))
	for range 600 * scale() {
		cases = append(cases, randomWalkPatterns(r))
	}

	walk := func(pats []string) ([]string, error) {
		var emitted []string
		err := fsutil.Walk(context.Background(), root, &fsutil.FilterOpt{ExcludePatterns: pats},
			func(path string, _ os.FileInfo, err error) error {
				if err != nil {
					return err
				}
				emitted = append(emitted, path)
				return nil
			})
		return emitted, err
	}
	// The unfiltered walk gives the order; each case is the subsequence of
	// it that the filtered walk reports.
	order, err := walk(nil)
	if err != nil || len(order) != len(treeEntries) {
		panic(fmt.Sprintf("unfiltered walk: %d entries, %v", len(order), err))
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n", fmt.Sprintf(header, runtime.Version()))
	b.WriteString("# entry <path> per tree entry in walk order (directories end with /), then\n")
	b.WriteString("# per case: case; pattern <p> per exclude pattern; emit <one 0/1 per entry,\n")
	b.WriteString("# 1 if the filtered walk reports it> or error.\n")
	isDir := map[string]bool{}
	for _, e := range treeEntries {
		isDir[strings.TrimSuffix(e, "/")] = strings.HasSuffix(e, "/")
	}
	for _, p := range order {
		if isDir[p] {
			p += "/"
		}
		fmt.Fprintf(&b, "entry %s\n", enc(p))
	}
	for _, pats := range cases {
		b.WriteString("case\n")
		for _, p := range pats {
			fmt.Fprintf(&b, "pattern %s\n", enc(p))
		}
		emitted, err := walk(pats)
		if err != nil {
			b.WriteString("error\n")
			continue
		}
		var bits bytes.Buffer
		next := 0
		for _, p := range order {
			if next < len(emitted) && emitted[next] == p {
				bits.WriteByte('1')
				next++
			} else {
				bits.WriteByte('0')
			}
		}
		if next != len(emitted) {
			panic("filtered walk is not a subsequence of the unfiltered one")
		}
		fmt.Fprintf(&b, "emit %s\n", bits.String())
	}
	return b.String()
}
