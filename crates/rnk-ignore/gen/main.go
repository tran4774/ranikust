// instantiate turns a pattern into a path it is likely to match.
func instantiate(r *rand.Rand, p string) string {
	p = strings.TrimPrefix(p, "!")
	var b strings.Builder
	for i := 0; i < len(p); i++ {
		switch c := p[i]; c {
		case '*':
			if i+1 < len(p) && p[i+1] == '*' {
				i++
				b.WriteString([]string{"", "a/", "a/b/", "x"}[r.IntN(4)])
			} else {
				b.WriteString([]string{"", "a", "ab", "x.y"}[r.IntN(4)])
			}
		case '?':
			b.WriteString([]string{"a", "z", "\xe2\x98\xba", "/"}[r.IntN(4)])
		case '\\':
			if i+1 < len(p) {
				i++
				b.WriteByte(p[i])
			}
		case '[':
			j := strings.IndexByte(p[i:], ']')
			if j > 1 {
				b.WriteByte(p[i+1+r.IntN(j-1)])
				i += j
			} else {
				b.WriteByte(c)
			}
		default:
			b.WriteByte(c)
		}
	}
	s := b.String()
	if r.IntN(3) == 0 {
		s += []string{"/c", "/a/b", "x", "/"}[r.IntN(4)]
	}
	if r.IntN(4) == 0 {
		s = filepath.Clean(s)
	}
	return s
}

func randomPaths(r *rand.Rand, pats []string) []string {
	var out []string
	for range 4 {
		out = append(out, randomPath(r))
	}
	for range 6 {
		out = append(out, instantiate(r, pats[r.IntN(len(pats))]))
	}
	return out
}

