func randomPattern(r *rand.Rand) string {
	var b strings.Builder
	switch r.IntN(10) {
	case 0:
		b.WriteString("!")
	case 1:
		b.WriteString("/")
	case 2:
		b.WriteString("./")
	case 3:
		b.WriteString("**/")
	}
	n := 1 + r.IntN(6)
	for range n {
		// Plain tokens are more common, so that patterns are often valid.
		if r.IntN(3) == 0 {
			b.WriteString(patTokens[r.IntN(len(patTokens))])
		} else {
			b.WriteString(patTokens[r.IntN(18)])
		}
	}
	switch r.IntN(8) {
	case 0:
		b.WriteString("/")
	case 1:
		b.WriteString("/**")
	}
	return b.String()
}

func randomPatterns(r *rand.Rand) []string {
	n := 1 + r.IntN(4)
	out := make([]string, 0, n)
	for range n {
		out = append(out, randomPattern(r))
	}
	return out
}

