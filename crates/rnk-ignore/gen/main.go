type rng struct{ lo, hi rune }

func ranges(t *unicode.RangeTable) []rng {
	var out []rng
	add := func(lo, hi rune) {
		if n := len(out); n > 0 && out[n-1].hi+1 == lo {
			out[n-1].hi = hi
			return
		}
		out = append(out, rng{lo, hi})
	}
	for _, r := range t.R16 {
		if r.Stride == 1 {
			add(rune(r.Lo), rune(r.Hi))
			continue
		}
		for c := rune(r.Lo); c <= rune(r.Hi); c += rune(r.Stride) {
			add(c, c)
		}
	}
	for _, r := range t.R32 {
		if r.Stride == 1 {
			add(rune(r.Lo), rune(r.Hi))
			continue
		}
		for c := rune(r.Lo); c <= rune(r.Hi); c += rune(r.Stride) {
			add(c, c)
		}
	}
	return out
}

// union merges the ranges of several tables.
func union(lists ...[]rng) []rng {
	var all []rng
	for _, l := range lists {
		all = append(all, l...)
	}
	sort.Slice(all, func(i, j int) bool { return all[i].lo < all[j].lo })
	var out []rng
	for _, r := range all {
		if n := len(out); n > 0 && out[n-1].hi+1 >= r.lo {
			if r.hi > out[n-1].hi {
				out[n-1].hi = r.hi
			}
			continue
		}
		out = append(out, r)
	}
	return out
}

func equal(a, b []rng) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

// canonicalName is regexp/syntax's canonicalName (go1.26.9).
func canonicalName(name string) string {
	var b []byte
	first := true
	for i := range len(name) {
		c := name[i]
		switch {
		case c == '_' || c == '-' || c == ' ':
			c = ' '
		case first:
			if 'a' <= c && c <= 'z' {
				c -= 'a' - 'A'
			}
			first = false
		default:
			if 'A' <= c && c <= 'Z' {
				c += 'a' - 'A'
			}
		}
		if c == ' ' {
			continue
		}
		b = append(b, c)
	}
	return string(b)
}

type entry struct {
	name   string   // canonical name
	negate bool     // the class is the complement of the union
	tables []string // base tables, by Go name
}

func tables() string {
	// Base tables: the two-letter categories, the scripts whose names are
	// canonical (Go looks names up after canonicalising them, so other
	// scripts are unreachable), and two synthetic ones.
	base := map[string][]rng{
		"Any":   {{0, unicode.MaxRune}},
		"Ascii": {{0, 0x7f}},
	}
	subcats := map[string][]string{}
	for k, t := range unicode.Categories {
		if len(k) == 2 && k != "LC" {
			base[k] = ranges(t)
			subcats[k[:1]] = append(subcats[k[:1]], k)
		}
	}
	for k, t := range unicode.Scripts {
		if canonicalName(k) == k {
			base[k] = ranges(t)
		}
	}
	// A category name resolves to its two-letter parts; check that the
	// union is exactly Go's table.
	resolve := func(cat string) []string {
		var parts []string
		switch {
		case cat == "LC":
			parts = []string{"Ll", "Lt", "Lu"}
		case len(cat) == 1:
			parts = append(parts, subcats[cat]...)
			sort.Strings(parts)
		default:
			parts = []string{cat}
		}
		var lists [][]rng
		for _, p := range parts {
			lists = append(lists, base[p])
		}
		if !equal(union(lists...), ranges(unicode.Categories[cat])) {
			panic("category " + cat + " is not the union of " + strings.Join(parts, ","))
		}
		return parts
	}

	// unicodeTable's lookup order: special names, categories, scripts,
	// category aliases.
	entries := map[string]entry{}
	addEntry := func(e entry) {
		if _, ok := entries[e.name]; !ok {
			entries[e.name] = e
		}
	}
	addEntry(entry{"Any", false, []string{"Any"}})
	addEntry(entry{"Assigned", true, []string{"Cn"}})
	addEntry(entry{"Ascii", false, []string{"Ascii"}})
	addEntry(entry{"Lc", false, resolve("LC")})
	for k := range unicode.Categories {
		if canonicalName(k) == k {
			addEntry(entry{k, false, resolve(k)})
		}
	}
	for k := range unicode.Scripts {
		if canonicalName(k) == k {
			addEntry(entry{k, false, []string{k}})
		}
	}
	for alias, actual := range unicode.CategoryAliases {
		addEntry(entry{canonicalName(alias), false, resolve(actual)})
	}

	names := make([]string, 0, len(entries))
	for n := range entries {
		names = append(names, n)
	}
	sort.Strings(names)
	verifyEntries(names, entries, base)

	baseNames := make([]string, 0, len(base))
	for n := range base {
		baseNames = append(baseNames, n)
	}
	sort.Strings(baseNames)
	index := map[string]int{}
	for i, n := range baseNames {
		index[n] = i
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// %s.\n", fmt.Sprintf(header, runtime.Version()))
	b.WriteString("//\n")
	b.WriteString("// Derived from the Go standard library (package unicode and\n")
	b.WriteString("// regexp/syntax's unicodeTable). Copyright 2009 The Go Authors.\n")
	b.WriteString("// Licensed under the BSD 3-Clause license; the data comes from the\n")
	b.WriteString("// Unicode Character Database, Unicode License v3.\n\n")
	b.WriteString("//! The Unicode classes Go's regexp accepts in `\\pX` and `\\p{Name}`, as Go\n")
	b.WriteString("//! defines them (not as the `regex` crate's own tables do).\n\n")
	fmt.Fprintf(&b, "/// The Unicode version of Go's `unicode` package.\n")
	fmt.Fprintf(&b, "#[cfg(test)]\npub(crate) const UNICODE_VERSION: &str = %q;\n\n", unicode.Version)
	b.WriteString("/// Names Go's `unicodeTable` accepts, after `canonicalName`, sorted: the\n")
	b.WriteString("/// name, whether the class is the complement, and the indices in [`TABLES`]\n")
	b.WriteString("/// whose union it is.\n")
	b.WriteString("#[rustfmt::skip]\n")
	b.WriteString("pub(crate) const NAMES: &[(&str, bool, &[usize])] = &[\n")
	for _, n := range names {
		e := entries[n]
		var idx []string
		for _, t := range e.tables {
			idx = append(idx, fmt.Sprint(index[t]))
		}
		fmt.Fprintf(&b, "    (%q, %v, &[%s]),\n", n, e.negate, strings.Join(idx, ", "))
	}
	b.WriteString("];\n\n")
	b.WriteString("/// Inclusive code point ranges, sorted and merged, by Go table name.\n")
	b.WriteString("#[rustfmt::skip]\n")
	fmt.Fprintf(&b, "pub(crate) const TABLES: [(&str, &[(u32, u32)]); %d] = [\n", len(baseNames))
	for _, n := range baseNames {
		fmt.Fprintf(&b, "    (\n        %q,\n        &[\n", n)
		line := "           "
		for _, r := range base[n] {
			item := fmt.Sprintf(" (0x%X, 0x%X),", r.lo, r.hi)
			if len(line)+len(item) > 100 {
				b.WriteString(line + "\n")
				line = "           "
			}
			line += item
		}
		b.WriteString(line + "\n        ],\n    ),\n")
	}
	b.WriteString("];\n")
	return b.String()
}

// verifyEntries compiles \p{name} with Go's regexp for every entry and
// checks it against the table on a sample of code points, so that the
// emulated lookup cannot drift from Go's.
func verifyEntries(names []string, entries map[string]entry, base map[string][]rng) {
	for _, n := range names {
		e := entries[n]
		re, err := regexp.Compile(`^\p{` + n + `}$`)
		if err != nil {
			panic(fmt.Sprintf("\\p{%s}: %v", n, err))
		}
		var lists [][]rng
		for _, t := range e.tables {
			lists = append(lists, base[t])
		}
		set := union(lists...)
		in := func(r rune) bool {
			for _, x := range set {
				if r >= x.lo && r <= x.hi {
					return true
				}
			}
			return false
		}
		check := func(r rune) {
			if r < 0 || r > unicode.MaxRune || (r >= 0xd800 && r <= 0xdfff) {
				return
			}
			if re.MatchString(string(r)) != (in(r) != e.negate) {
				panic(fmt.Sprintf("\\p{%s} disagrees at U+%04X", n, r))
			}
		}
		for r := rune(0); r <= unicode.MaxRune; r += 97 {
			check(r)
		}
		for _, x := range set {
			check(x.lo - 1)
			check(x.lo)
			check(x.hi)
			check(x.hi + 1)
		}
	}
	// Names Go rejects must not be in the table.
	for _, n := range []string{"Old_Italic", "Olditalic", "Foo", "", "LC"} {
		_, err := regexp.Compile(`\p{` + n + `}`)
		_, ok := entries[canonicalName(n)]
		if (err == nil) != ok {
			panic("name lookup disagrees for " + n)
		}
	}
}

