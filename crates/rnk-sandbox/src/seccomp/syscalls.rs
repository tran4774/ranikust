//! System call names to numbers for the architecture ranikust is built for,
//! from `libc` (ADR-0009). A name `libc` does not know is unknown to a
//! profile: skipped under `SCMP_ACT_ALLOW`, refused otherwise (ADR-0109).
//! The lists are what `libc`'s `SYS_*` constants name for each architecture
//! and C library; the numbers are the kernel's, the same for both.

/// The number of the system call `name`, if `libc` names it here.
pub(super) fn number(name: &str) -> Option<u32> {
    COMMON
        .iter()
        .chain(LIBC)
        .find(|(n, _)| *n == name)
        .and_then(|&(_, nr)| u32::try_from(nr).ok())
}

/// Every system call `libc` names here, with its number.
pub(super) fn all() -> impl Iterator<Item = (&'static str, u32)> {
    COMMON
        .iter()
        .chain(LIBC)
        .filter_map(|&(name, nr)| Some((name, u32::try_from(nr).ok()?)))
}

